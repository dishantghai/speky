"""Git helpers. Everything degrades to NO_VCS when the project is not a git repository."""
import hashlib
import subprocess
from pathlib import Path
from typing import List, Optional

NO_VCS = "NO_VCS"


def _git(root: Path, *args: str) -> Optional[str]:
    try:
        result = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)
    except FileNotFoundError:
        return None
    return result.stdout if result.returncode == 0 else None


def head(root: Path) -> str:
    out = _git(root, "rev-parse", "HEAD")
    return out.strip() if out else NO_VCS


def is_repo(root: Path) -> bool:
    return _git(root, "rev-parse", "--is-inside-work-tree") is not None


def changed_files(root: Path, base: str) -> List[str]:
    """Files changed since `base`: committed, staged, unstaged and untracked (excluding .speky/)."""
    if base in (None, NO_VCS) or not is_repo(root):
        return []
    files = set()
    committed = _git(root, "diff", "--name-only", f"{base}..HEAD")
    files.update((committed or "").splitlines())
    working = _git(root, "status", "--porcelain=v1", "--untracked-files=all")
    for line in (working or "").splitlines():
        path = line[3:]
        if " -> " in path:
            path = path.split(" -> ", 1)[1]
        files.add(path.strip('"'))
    return sorted(f for f in files if f and not f.startswith(".speky/") and not _is_cache(f))


# Generated by running tests/builds; never part of "the code changed since verification"
CACHE_PARTS = {"__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".tox", "node_modules",
               ".next", ".turbo", ".cache", "coverage", "htmlcov", ".coverage", ".DS_Store",
               "dist", "build", ".dart_tool", "target"}


def _is_cache(path: str) -> bool:
    parts = path.split("/")
    return any(p in CACHE_PARTS for p in parts) or path.endswith((".pyc", ".pyo"))


def tree_fingerprint(root: Path) -> str:
    """Identifies the current code: HEAD + uncommitted diff + untracked file contents
    (excluding .speky/ and caches that running tests create)."""
    if not is_repo(root):
        return NO_VCS
    diff = _git(root, "diff", "HEAD", "--", ".", ":(exclude).speky") or ""
    untracked = _git(root, "ls-files", "--others", "--exclude-standard", "--", ".", ":(exclude).speky") or ""
    h = hashlib.sha1(diff.encode())
    for rel in sorted(p for p in untracked.splitlines() if p and not _is_cache(p)):
        h.update(rel.encode())
        try:
            h.update((Path(root) / rel).read_bytes()[:1_000_000])
        except OSError:
            pass
    return f"{head(root)[:12]}+{h.hexdigest()[:12]}"
