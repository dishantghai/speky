"""Dependencies and implementation order (v2's sequence, infer-deps, mark-foundation, reset-deps,
fix-circular-deps). Dependencies live in each item's `status.json` (`dependencies`), as in v2.

Inferring dependencies is judgement work: the agent proposes them (speky-plan skill) and records them
with `speky deps add`. Order is a topological sort, ties broken by priority then ID; foundation items
first. IDs never change (no renumbering): the order is computed, not baked into IDs.
"""
from datetime import datetime
from typing import List

from . import graph
from .errors import SpekyError
from .items import DONE_STATUSES, PRIORITY_ORDER, Item, Project


def add(project: Project, ref: str, deps: List[str]) -> dict:
    item = project.find(ref)
    status = item.load_status()
    current = [str(d) for d in status.get("dependencies", []) or []]
    for d in deps:
        dep = project.find(d)
        if dep.id == item.id:
            raise SpekyError("self_dependency", f"{item.id} cannot depend on itself.")
        if dep.id not in current:
            current.append(dep.id)
    status["dependencies"] = current
    status.pop("foundation", None) if current else None
    item.save_status(status)
    cycles = [c for c in graph.cycles(project) if item.id in c]
    return {"item": item.id, "dependencies": current, "cycles": cycles,
            **({"warning": "this creates a dependency cycle"} if cycles else {})}


def remove(project: Project, ref: str, deps: List[str]) -> dict:
    item = project.find(ref)
    status = item.load_status()
    drop = {project.find(d).id if project.try_find(d) else d for d in deps}
    status["dependencies"] = [d for d in status.get("dependencies", []) or [] if str(d) not in drop]
    item.save_status(status)
    return {"item": item.id, "dependencies": status["dependencies"]}


def clear(project: Project, ref: str = None) -> dict:
    items = project.items() if ref is None else [project.find(ref)]
    for item in items:
        status = item.load_status()
        status["dependencies"] = []
        item.save_status(status)
    return {"cleared": [i.id for i in items]}


def foundation(project: Project, ref: str) -> dict:
    """A foundation item depends on nothing and comes first in the order."""
    item = project.find(ref)
    status = item.load_status()
    status["dependencies"] = []
    status["foundation"] = True
    item.save_status(status)
    return {"item": item.id, "foundation": True}


def order(project: Project, include_done: bool = True) -> List[dict]:
    infos = {i["id"]: {**i, "foundation": bool(project.find(i["id"]).load_status().get("foundation"))}
             for i in graph.statuses(project).values()}
    if not include_done:
        infos = {k: v for k, v in infos.items() if v["status"] not in DONE_STATUSES}
    known = set(infos)
    indegree = {k: len([d for d in v["dependencies"] if d in known]) for k, v in infos.items()}

    def key(i):
        return (0 if infos[i]["foundation"] else 1, PRIORITY_ORDER.get(str(infos[i]["priority"]), 2), i)

    queue = sorted([k for k, n in indegree.items() if n == 0], key=key)
    result = []
    while queue:
        cur = queue.pop(0)
        result.append(cur)
        for k, v in infos.items():
            if cur in v["dependencies"] and k in indegree:
                indegree[k] -= 1
                if indegree[k] == 0:
                    queue.append(k)
                    queue.sort(key=key)
    remaining = sorted([k for k in infos if k not in result], key=key)  # in a cycle
    all_info = graph.statuses(project)
    out = []
    for n, k in enumerate(result + remaining, 1):
        v = infos[k]
        out.append({"position": n, "id": k, "title": v["title"], "kind": v["kind"], "status": v["status"],
                    "priority": v["priority"], "dependencies": v["dependencies"],
                    "foundation": v["foundation"], "in_cycle": k in remaining,
                    "blocked_by": graph.blocked_by(v, all_info) if v["status"] not in DONE_STATUSES else []})
    return out


def export(project: Project) -> str:
    """Write `.speky/roadmap.md` (the file v2's `sequence --export` wrote)."""
    rows = order(project)
    cycles = graph.cycles(project)
    lines = ["# Implementation order", "", f"_Generated by `speky order --export` on "
             f"{datetime.now().isoformat(timespec='minutes')} from dependencies and priorities._", ""]
    by_p = {}
    for r in rows:
        by_p[str(r["priority"])] = by_p.get(str(r["priority"]), 0) + 1
    lines += [f"{len(rows)} items · " + " · ".join(f"{p}: {n}" for p, n in sorted(by_p.items())), ""]
    if cycles:
        lines += ["## Dependency cycles (fix with `speky deps remove`)"] + \
                 [f"- {' → '.join(c)}" for c in cycles] + [""]
    lines.append("## Order")
    for r in rows:
        mark = "x" if r["status"] in DONE_STATUSES else ("~" if r["status"] in ("in_progress", "review") else " ")
        deps = f" — after {', '.join(r['dependencies'])}" if r["dependencies"] else ""
        found = " · foundation" if r["foundation"] else ""
        lines.append(f"{r['position']}. [{mark}] **{r['id']}** {r['title']} [{r['priority']}]{found}{deps}")
    path = project.dir / "roadmap.md"
    path.write_text("\n".join(lines) + "\n")
    return str(path.relative_to(project.root))
