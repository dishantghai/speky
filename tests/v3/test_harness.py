import json

from speky_core import harness

LEGACY_V2 = ("# CLAUDE.md - Auto-generated by SPEKY\n\n# SPEKY Project Rules\n\nhuge rules\n\n---\n\n"
             "# USER RULES\n\n"
             "Add your custom IDE rules below this line. They will be preserved when SPEKY updates.\n"
             "Example:\n- Always use TypeScript strict mode\n- Prefer async/await over promises\n"
             "- Use descriptive variable names\n- Use pnpm, never npm\n"
             "\n---\n\n## Project Context\n\nproduct\n")


def test_claude_code_setup_check_remove(project):
    root = project.root
    (root / ".claude").mkdir()
    (root / ".claude" / "settings.json").write_text(json.dumps(
        {"permissions": {"allow": ["Bash(ls)"]},
         "hooks": {"SessionStart": [{"matcher": "startup", "hooks": [{"type": "command", "command": "echo hi"}]}]}}))
    (root / "CLAUDE.md").write_text("# My notes\n\n- be nice\n")

    result = harness.setup(project, "claude-code")
    assert result["check"]["status"] == "current"
    assert (root / ".claude" / "skills" / "speky-validate" / "SKILL.md").exists()
    claude = (root / "CLAUDE.md").read_text()
    assert claude.startswith("# My notes\n\n- be nice\n") and "BEGIN SPEKY v:3 profile:minimal" in claude
    settings = json.loads((root / ".claude" / "settings.json").read_text())
    assert settings["permissions"] == {"allow": ["Bash(ls)"]}
    commands = [h["command"] for e in settings["hooks"]["SessionStart"] for h in e["hooks"]]
    assert "echo hi" in commands and any("speky prime --hook-json" in c for c in commands)
    assert "claude-code" in project.config["harnesses"]

    # idempotent
    harness.setup(project, "claude-code")
    assert (root / "CLAUDE.md").read_text().count("BEGIN SPEKY v:3") == 1
    settings = json.loads((root / ".claude" / "settings.json").read_text())
    assert sum("speky prime" in h["command"] for e in settings["hooks"]["SessionStart"] for h in e["hooks"]) == 1

    # stale detection
    (root / ".claude" / "skills" / "speky" / "SKILL.md").write_text("edited")
    assert harness.check(project, "claude-code")["status"] == "stale"

    harness.remove(project, "claude-code")
    assert (root / "CLAUDE.md").read_text() == "# My notes\n\n- be nice\n"
    assert not (root / ".claude" / "skills" / "speky").exists()
    settings = json.loads((root / ".claude" / "settings.json").read_text())
    assert settings["hooks"]["SessionStart"][0]["hooks"][0]["command"] == "echo hi"
    assert harness.check(project, "claude-code")["status"] == "missing"


def test_legacy_v2_rules_file_is_replaced_and_backed_up(project):
    root = project.root
    (root / "CLAUDE.md").write_text(LEGACY_V2)
    (project.dir / "context").mkdir()
    (project.dir / "context" / "context.json").write_text(json.dumps({"enabled_ides": ["windsurf", "claude-code"]}))
    harness.setup(project, "claude-code")
    claude = (root / "CLAUDE.md").read_text()
    assert "huge rules" not in claude and "- Use pnpm, never npm" in claude
    assert len(claude.splitlines()) < 30
    backups = [p for p in (project.dir / "backups").iterdir() if p.name != ".gitignore"]
    assert backups and backups[0].read_text() == LEGACY_V2
    assert (project.dir / "backups" / ".gitignore").read_text().strip().endswith("*")
    ctx = json.loads((project.dir / "context" / "context.json").read_text())
    assert ctx["enabled_ides"] == ["windsurf"]


