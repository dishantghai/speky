def test_codex_and_agents_md(project):
    root = project.root
    (root / "AGENTS.md").write_text("# Team rules\n")
    harness.setup(project, "codex")
    assert (root / ".agents" / "skills" / "speky" / "SKILL.md").exists()
    agents = (root / "AGENTS.md").read_text()
    assert agents.startswith("# Team rules") and "profile:full" in agents
