from speky import IDEIntegration

BEGIN, END = IDEIntegration.BLOCK_BEGIN, IDEIntegration.BLOCK_END


def write(tmp_path, context="Product A"):
    IDEIntegration(tmp_path, ide="claude-code").update_context_file(context, target_ide="claude-code")
    return (tmp_path / "CLAUDE.md").read_text()


def test_new_file_contains_only_the_block(tmp_path):
    text = write(tmp_path)
    assert text.startswith(BEGIN) and text.rstrip().endswith(END)
    assert "Product A" in text


def test_users_own_claude_md_is_kept_and_block_appended(tmp_path):
    (tmp_path / "CLAUDE.md").write_text("# My rules\n\n- Use tabs\n")
    text = write(tmp_path)
    assert text.startswith("# My rules\n\n- Use tabs\n")
    assert BEGIN in text and "Product A" in text


def test_rewrite_replaces_only_the_block(tmp_path):
    write(tmp_path)
    path = tmp_path / "CLAUDE.md"
    path.write_text("Above\n\n" + path.read_text() + "\nBelow\n")
    text = write(tmp_path, context="Product B")
    assert text.startswith("Above\n\n") and text.endswith("\nBelow\n")
    assert "Product B" in text and "Product A" not in text
    assert text.count(BEGIN) == 1 and text.count(END) == 1


def test_legacy_speky_file_keeps_user_rules_and_is_backed_up(tmp_path):
    legacy = (
        "# CLAUDE.md - Auto-generated by SPEKY\n\n# SPEKY Project Rules\n\nold rules\n\n---\n\n"
        "# USER RULES\n\n"
        "Add your custom IDE rules below this line. They will be preserved when SPEKY updates.\n"
        "Example:\n- Always use TypeScript strict mode\n- Prefer async/await over promises\n"
        "- Use descriptive variable names\n- Never touch the payments module\n"
        "\n---\n\n## Project Context\n\nOld product\n"
    )
    (tmp_path / "CLAUDE.md").write_text(legacy)
    text = write(tmp_path)
    assert "- Never touch the payments module" in text.split(BEGIN)[0]
    assert "old rules" not in text and "Old product" not in text
    backups = [p for p in (tmp_path / ".speky" / "backups").iterdir() if p.name != ".gitignore"]
    assert len(backups) == 1 and backups[0].read_text() == legacy


def test_extract_managed_block_round_trip(tmp_path):
    ide = IDEIntegration(tmp_path, ide="claude-code")
    ide.update_context_file("Product A", target_ide="claude-code")
    block = IDEIntegration.extract_managed_block((tmp_path / "CLAUDE.md").read_text())
    assert block == ide.build_rules_content("claude-code", "Product A").strip("\n")
